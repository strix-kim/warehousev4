-- Разделение «Zoom / PPT» (с20, по требованию прораба). В образце это была одна
-- строка, но на площадке это две разные работы: Zoom ведёт трансляцию, PPT
-- листает презентацию, и стоят на них разные люди. Одной строкой их не
-- расставить — человека пришлось бы записывать дважды в одну клетку.
--
-- DELETE по живой строке справочника объявлен: прораб сам попросил разделить,
-- и строка «Zoom / PPT» после этого не нужна. Планы это не задевает — строка
-- плана хранит свою копию имени, ссылки на справочник нет (миграция
-- 20260824120000). Уже расставленные планы с «Zoom / PPT» останутся как были.
--
-- «Камеры / PTZ» НЕ трогаем: там косая черта означает тип камеры, а не две
-- разные работы — это одна позиция.
delete from public.position_catalog where lower(btrim(name)) = 'zoom / ppt';

insert into public.position_catalog (name, role) values
  ('Zoom', 'technician'),
  ('PPT', 'technician')
on conflict do nothing;

notify pgrst, 'reload schema';
