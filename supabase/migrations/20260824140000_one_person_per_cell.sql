-- Одна ячейка — один человек (с20, решение прораба). Стопка слотов в клетке и
-- вакансия-запись упраздняются обе: на бумажном образце трое операторов в зале
-- это ТРИ ПОДСТРОКИ, а не три чипа в одной клетке, а прочерк — просто пустая
-- клетка. Значит «сколько людей на позиции» задаётся числом строк матрицы, и
-- второго способа сказать то же самое быть не должно.
--
-- Следствие для вакансий: пустая ячейка И ЕСТЬ вакансия. Запись с
-- employee_id null больше не нужна — «свободно» считается по клеткам без
-- записи, а не по записям без человека.
--
-- Оба DELETE ниже объявлены прорабом: вакансии он упразднил сам, а стопки
-- в клетках существовали только в его тестовых расстановках. На проде на момент
-- миграции в hall_assignments 2 строки, из них 0 вакансий и 0 лишних в клетке —
-- то есть фактически оба запроса не заденут ничего. В миграции они остаются:
-- на любой другой базе (или после отката к старому коду) чистить придётся.

-- 1. Вакансии-записи: место без человека больше не хранится строкой.
delete from public.hall_assignments where employee_id is null;

-- 2. Стопки: в клетке остаётся САМАЯ РАННЯЯ запись, остальные уходят. Ранняя,
-- а не произвольная: первый, кого в клетку поставили, и есть тот, кого имели
-- в виду; ключ полный (created_at, id) — пачечная вставка кладёт несколько
-- строк одной миллисекундой.
delete from public.hall_assignments as extra
using public.hall_assignments as keeper
where extra.position_id = keeper.position_id
  and extra.hall_id = keeper.hall_id
  and (keeper.created_at, keeper.id) < (extra.created_at, extra.id);

-- 3. Человек в ячейке обязателен: «ячейка без человека» теперь выражается
-- отсутствием строки, и NULL стал бы вторым способом сказать то же самое.
alter table public.hall_assignments alter column employee_id set not null;

-- 4. Частичный индекс «человек в клетке один раз» больше не нужен: его условие
-- поглощено более сильным правилом из пункта 5. sort_order уходит вместе со
-- стопкой — сортировать внутри клетки стало нечего.
drop index if exists public.hall_assignments_person_per_cell_key;
alter table public.hall_assignments drop column if exists sort_order;

-- 5. Само правило, и оно живёт в БАЗЕ, а не в React: две вкладки, назначившие
-- разных людей в одну клетку, обязаны разойтись отказом, а не тем, что кто-то
-- перетрёт другого молча.
create unique index if not exists hall_assignments_cell_key
  on public.hall_assignments (position_id, hall_id);

