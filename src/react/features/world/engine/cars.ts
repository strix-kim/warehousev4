const U = 4.5   // длина Cobalt в сцене: под неё рассчитаны шаги раскладки гаража

type Role = 'body' | 'glass' | 'dark' | 'lamp' | 'red'
type Part = readonly [role: Role, w: number, h: number, d: number, x: number, y: number, z: number, deg?: number]
type Wheel = readonly [dia: number, w: number, x: number, z: number]
// deck — высота пола платформы: на него встают кейсы
type Spec = { L: number; deck?: number; parts: readonly Part[]; wheels: readonly Wheel[] }

// Наклонное стекло по силуэту из спецификации: верхняя плоскость клина идёт от (zLow, yLow)
// у капота/багажника до (zHigh, yHigh) у крыши. Толщина клина — 1,6 высоты прямоугольного
// треугольника под стеклом: он закрывает пустоту между стеклом, поясом и салоном (с запасом —
// иначе в перспективе у пояса видны щели), лишнее уходит внутрь кузова. Перёд ниже — наклон положительный.
function slope(w: number, zLow: number, yLow: number, zHigh: number, yHigh: number): Part {
  const dz = Math.abs(zHigh - zLow), dy = yHigh - yLow, len = Math.hypot(dz, dy), t = (dz * dy / len) * 1.6
  const a = Math.atan2(dy, dz) * Math.sign(zLow - zHigh), ny = Math.cos(a), nz = Math.sin(a)
  return ['glass', w, t, len, 0, (yLow + yHigh) / 2 - (t / 2) * ny, (zLow + zHigh) / 2 - (t / 2) * nz, THREE.MathUtils.radToDeg(a)]
}

