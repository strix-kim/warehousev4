// Длина машины в метрах сцены: по ней гараж выставляет передки в проёмах
export function carLength(car: WorldCar) {
  return SPEC[carKind(car.brand, car.model)].L * U
}

const CAR_SINK = 0.07   // на сколько (в долях длины) капот и багажник уходят в скруглённый кузов

// cargo — кейсы на полу платформы; у машины без платформы их нет
export function makeCar(ctx: WorldCtx, car: WorldCar, cargo = false) {
  const g = new THREE.Group(), k = kit(ctx), s = SPEC[carKind(car.brand, car.model)], n = s.L * U
  const { carGlass, dark, lamp, red, tire, steel } = ctx.style.roles
  // Цвет кузова — данные машины, палитра его не трогает
  const role = { body: mat(ctx.style, carHex(car.color)), glass: carGlass, dark, lamp, red }
  let top = 0
  for (const [r, w, h0, d, x, y0, z, deg = 0] of s.parts) {
    let h = h0, y = y0
    top = Math.max(top, (y + h / 2) * n)
    // Тонкая панель кузова на скруглённом объёме висела бы козырьком. Крыша — плита со скруглёнными
    // в плане углами; капот и багажник утолщаются вниз, внутрь кузова, и скругляются вместе с ним.
    if (r === 'body' && !deg && h < 0.05 && w > 0.2) {
      if (y > 0.28) { k.slab(role[r], w * n, h * n, d * n, x * n, (y - h / 2) * n, z * n); continue }
      y -= CAR_SINK / 2; h += CAR_SINK
    }
    k(role[r], w * n, h * n, d * n, x * n, (y - h / 2) * n, z * n, THREE.MathUtils.degToRad(deg))
  }
  // Колесо — шина и тонкий диск на внешней стороне; контура нет
  for (const [dia, w, x, z] of s.wheels) for (const sx of [-1, 1]) {
    const r = (dia / 2) * n
    k.cyl(tire, r, w * n, sx * x * n, r, z * n)
    k.cyl(steel, r * 0.6, 0.006 * n, sx * (x + w / 2 + 0.002) * n, r, z * n)
  }
  if (cargo && s.deck !== undefined) { const y0 = s.deck * n; crate(ctx, k, -0.4, y0, -1.2); crate(ctx, k, 0.4, y0, -0.4) }
  k.into(g)
  g.userData = { top }
  return g
}
