// Общие мелочи для запросов к PostgREST через supabase-js.

// В шаблоне LIKE/ILIKE `%` и `_` — подстановочные знаки, а `\` — знак
// экранирования. Пользовательскую строку нельзя класть в шаблон сырой: запрос
// «отчёт_2026» совпал бы и с «отчёт 2026», а один символ `%` вернул бы вообще
// всё. Обратная косая идёт первой, иначе она экранировала бы уже добавленные
// косые.
export function escapeLikePattern(value: string) {
  return value.replace(/[\\%_]/g, (char) => `\\${char}`)
}

// Значение внутри логического выражения `.or(...)`: там PostgREST сам разбирает
// строку по запятым и скобкам, поэтому площадка «Hyatt, зал 2» развалила бы
// фильтр на два условия, а «Зал (малый)» — на незакрытую скобку. Спасают двойные
// кавычки, внутри которых экранируются только `"` и `\`.
//
// Порядок с escapeLikePattern важен и обратный не работает: сначала шаблон LIKE
// (внутренний слой), потом кавычки (транспорт). Обратная косая из первого слоя
// удваивается вторым, PostgREST снимает удвоение — и до LIKE доезжает ровно то,
// что нужно.
export function quoteFilterValue(value: string) {
  return `"${value.replace(/["\\]/g, (char) => `\\${char}`)}"`
}
