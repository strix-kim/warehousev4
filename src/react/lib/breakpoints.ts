// Единственный источник мобильной границы для JS: по ней считаются размер
// страницы каталога и списков, а размер страницы участвует в ключе кэша —
// расхождение двух копий превращает прогрев в мёртвый.
//
// ВНИМАНИЕ: у этой границы есть пара в CSS — медиазапрос `820px`
// в `src/react/styles.css`. Импортировать константу в CSS нечем, поэтому
// значения меняются руками синхронно: правишь здесь — правишь и там.
//
// Границ в CSS теперь ДВЕ, и путать их нельзя: 820 — оболочка (нижняя навигация,
// карточки вместо таблиц, тач-размеры), 700 — телефонная раскладка редактора
// (табы, одна колонка, плавающая полоса). JS читает только 820; редактор эту
// константу не импортирует вовсе.
export const MOBILE_BREAKPOINT = 820

export const MOBILE_MEDIA_QUERY = `(max-width: ${MOBILE_BREAKPOINT}px)`

// Широкий экран редактора: с этой ширины каталог получает третью колонку —
// рельс категорий вместо селекта в тулбаре. Пара в CSS — медиазапрос `1800px`
// в `styles.css`, правится руками синхронно, как и 820.
//
// Почему выбор делается в разметке, а не `display: none`: тулбар считает свои
// колонки селектором `:has(.app-select + .app-select)`, и спрятанный стилями
// селект остался бы для него существующим — раскладка поехала бы.
export const WIDE_EDITOR_BREAKPOINT = 1800

export const WIDE_EDITOR_MEDIA_QUERY = `(min-width: ${WIDE_EDITOR_BREAKPOINT}px)`
